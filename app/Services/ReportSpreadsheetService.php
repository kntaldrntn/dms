<?php

namespace App\Services;

use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;
use OpenSpout\Common\Entity\Row;
use OpenSpout\Common\Entity\Style\Style;
use OpenSpout\Writer\XLSX\Options;
use OpenSpout\Writer\XLSX\Writer;
use RuntimeException;
use Symfony\Component\HttpFoundation\BinaryFileResponse;
use Throwable;

/** The dashboard's printable reports as an Excel file: same rows and columns, no personal data. */
class ReportSpreadsheetService
{
    private const HEADINGS = ['Date', 'Barcode', 'Document type', 'Source', 'Subject matter', 'Office', 'Total time (days)'];

    /** Column widths in Excel characters, in HEADINGS order. */
    private const WIDTHS = [14, 18, 24, 26, 60, 10, 16];

    /**
     * @param  list<array<string, mixed>>  $rows  The report rows built by DashboardReportController.
     */
    public function download(string $title, string $dateRange, array $rows, string $generatedBy, string $generatedOn): BinaryFileResponse
    {
        $path = tempnam(sys_get_temp_dir(), 'dms-report-');
        if ($path === false) {
            throw new RuntimeException('A temporary file for the report could not be created.');
        }

        try {
            $options = new Options;
            foreach (self::WIDTHS as $index => $width) {
                $options->setColumnWidth($width, $index + 1);
            }
            $writer = new Writer($options);
            $writer->openToFile($path);

            $bold = (new Style)->setFontBold();
            $writer->addRow(Row::fromValues(['City Government of San Fernando'], (new Style)->setFontBold()->setFontSize(13)));
            $writer->addRow(Row::fromValues([$title], $bold));
            $writer->addRow(Row::fromValues([$dateRange.' · '.count($rows).' document'.(count($rows) === 1 ? '' : 's')]));
            $writer->addRow(Row::fromValues([]));
            $writer->addRow(Row::fromValues(self::HEADINGS, $bold));

            $wrap = (new Style)->setShouldWrapText();
            foreach ($rows as $row) {
                $writer->addRow(Row::fromValues([
                    $row['date'],
                    $row['barcode'],
                    $row['details_hidden'] ? '' : (string) $row['document_type'],
                    (string) ($row['source_name'] ?? ''),
                    (string) $row['subject_matter'],
                    (string) $row['department'],
                    (float) $row['total_days'],
                ], $wrap));
            }

            $writer->addRow(Row::fromValues([]));
            $writer->addRow(Row::fromValues(["Generated by {$generatedBy} on {$generatedOn}"]));
            $writer->close();
        } catch (Throwable $exception) {
            @unlink($path);
            Log::error('The report spreadsheet could not be written.', ['title' => $title, 'message' => $exception->getMessage()]);

            throw $exception;
        }

        return response()->download($path, Str::slug($title).'-'.now('Asia/Manila')->format('Ymd').'.xlsx', [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        ])->deleteFileAfterSend();
    }
}
